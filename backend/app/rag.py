"""Retrieval-Augmented Generation over the verified scheme data.

1. schemes.json is split into small chunks (about / benefit / eligibility / documents / steps / helpline / each FAQ),
   each carrying its official source URL and last-verified date.
2. Chunks are indexed in the best available vector store:
      FAISS + multilingual sentence-transformers  →  ChromaDB  →  pure-Python TF-IDF (always available).
3. Intent keywords (shared intents.json) + vector similarity pick the scheme and topic.
4. The answer is generated by the restricted LLM (if configured) from ONLY the retrieved chunks,
   otherwise composed directly from the chunk text. Unknown → "Mujhe iski pakki jaankari nahi hai".
"""
from __future__ import annotations

import logging
import math
import re
from collections import Counter
from functools import lru_cache

from . import config
from .adapters import llm
from .data import get_scheme, intents, pick, schemes
from .nlp import LETTERS, detect_language, has_phrase, normalize_dialect

log = logging.getLogger("bolo.rag")
LANGS = ("hi", "hl", "en")

UNSURE = {
    "hi": "माफ़ कीजिए, मुझे इसकी पक्की जानकारी नहीं है। मैं अंदाज़ा नहीं लगाऊँगा। कृपया हेल्पलाइन पर फ़ोन करें या किसी सहायक से बात करें।",
    "hl": "Maaf kijiye, mujhe iski pakki jaankari nahi hai. Main andaaza nahi lagaunga. Kripya helpline par phone karein ya kisi sahayak se baat karein.",
    "en": "Sorry, I don't have verified information about this, and I won't guess. Please call the helpline or talk to a human helper.",
}
WHICH = {
    "hi": "आप किस योजना के बारे में पूछ रहे हैं? पीएम-किसान, आयुष्मान भारत या लाड़ली बहना?",
    "hl": "Aap kis yojana ke baare mein pooch rahe hain? PM-Kisan, Ayushman Bharat ya Ladli Behna?",
    "en": "Which scheme are you asking about? PM-Kisan, Ayushman Bharat or Ladli Behna?",
}


# ------------------------------------------------------------------ chunking
@lru_cache
def build_chunks() -> list[dict]:
    """Read-only, cached list of chunks."""
    chunks = []
    for s in schemes():
        def add(topic: str, texts: dict[str, str], extra_id: str = "") -> None:
            chunks.append({
                "id": f"{s['id']}:{topic}{extra_id}", "scheme": s["id"], "topic": topic, "text": texts,
                "source": {"title": s["sourceName"], "url": s["officialUrl"], "lastVerified": s["lastVerified"]},
            })

        add("about", {l: f"{pick(s['name'], l)}. {pick(s['simple'], l)}" for l in LANGS})
        add("benefit", {l: pick(s["benefit"]["text"], l) for l in LANGS})
        add("eligibility", {l: "✅ " + "\n✅ ".join(pick(s["eligibility"]["yes"], l)) + "\n❌ " + "\n❌ ".join(pick(s["eligibility"]["no"], l)) for l in LANGS})
        add("documents", {l: "\n".join(f"{i + 1}. {d['icon']} {pick(d['name'], l)}" for i, d in enumerate(s["documents"])) for l in LANGS})
        add("apply", {l: "\n".join(f"{i + 1}. {st}" for i, st in enumerate(pick(s["steps"], l))) for l in LANGS})
        add("helpline", {l: f"{pick(s['helpline']['label'], l)}: 📞 {s['helpline']['number']}" for l in LANGS})
        for f in s.get("faqs", []):
            add(f["topic"], f["a"], f":{f['id']}")
            chunks[-1]["keywords"] = f["keywords"]
    return chunks


def _tokens(text: str) -> list[str]:
    return re.findall(f"[{LETTERS}0-9]+", text.lower())


# ------------------------------------------------------------------ vector stores
class TfidfStore:
    """Dependency-free fallback: TF-IDF cosine over all language variants of a chunk."""
    name = "tfidf"

    def __init__(self, chunks: list[dict]):
        self.chunks = chunks
        docs = [_tokens(" ".join(c["text"].values())) for c in chunks]
        df = Counter(t for d in docs for t in set(d))
        n = len(docs)
        self.idf = {t: math.log((n + 1) / (c + 1)) + 1 for t, c in df.items()}
        self.vecs = [self._vec(d) for d in docs]

    def _vec(self, toks: list[str]) -> dict[str, float]:
        tf = Counter(toks)
        v = {t: c * self.idf.get(t, 1.0) for t, c in tf.items()}
        norm = math.sqrt(sum(x * x for x in v.values())) or 1.0
        return {t: x / norm for t, x in v.items()}

    def search(self, query: str, k: int = 4) -> list[tuple[dict, float]]:
        q = self._vec(_tokens(query))
        scored = [(c, sum(q.get(t, 0) * w for t, w in v.items())) for c, v in zip(self.chunks, self.vecs)]
        return sorted(scored, key=lambda x: x[1], reverse=True)[:k]


class FaissStore:
    name = "faiss"

    def __init__(self, chunks: list[dict]):
        import faiss  # type: ignore
        from sentence_transformers import SentenceTransformer  # type: ignore

        self.chunks = chunks
        self.model = SentenceTransformer(config.EMBEDDING_MODEL)
        emb = self.model.encode([" ".join(c["text"].values()) for c in chunks], normalize_embeddings=True)
        self.index = faiss.IndexFlatIP(emb.shape[1])
        self.index.add(emb)

    def search(self, query: str, k: int = 4):
        q = self.model.encode([query], normalize_embeddings=True)
        scores, ids = self.index.search(q, k)
        return [(self.chunks[i], float(s)) for i, s in zip(ids[0], scores[0]) if i >= 0]


class ChromaStore:
    name = "chroma"

    def __init__(self, chunks: list[dict]):
        import chromadb  # type: ignore

        self.chunks = {c["id"]: c for c in chunks}
        self.col = chromadb.Client().get_or_create_collection("schemes", metadata={"hnsw:space": "cosine"})
        self.col.upsert(ids=list(self.chunks), documents=[" ".join(c["text"].values()) for c in chunks])

    def search(self, query: str, k: int = 4):
        r = self.col.query(query_texts=[query], n_results=k)
        return [(self.chunks[i], 1 - d) for i, d in zip(r["ids"][0], r["distances"][0])]


@lru_cache
def store():
    chunks = build_chunks()
    order = {"auto": ["faiss", "chroma", "tfidf"], "faiss": ["faiss", "tfidf"], "chroma": ["chroma", "tfidf"]}.get(config.VECTOR_STORE, ["tfidf"])
    for name in order:
        try:
            s = {"faiss": FaissStore, "chroma": ChromaStore, "tfidf": TfidfStore}[name](chunks)
            log.info("Vector store: %s (%d chunks)", s.name, len(chunks))
            return s
        except Exception as e:  # missing optional dependency / model download failure
            log.info("Vector store %s unavailable: %s", name, e)
    return TfidfStore(chunks)


# ------------------------------------------------------------------ retrieval + answer
def _count(text: str, words: list[str]) -> int:
    return sum(has_phrase(text, w) for w in words)


def retrieve(query: str, context_scheme_id: str | None = None) -> dict:
    q = query.lower()
    it = intents()
    scheme_scores = sorted(((s, _count(q, s["keywords"])) for s in schemes()), key=lambda x: x[1], reverse=True)
    scheme, scheme_score = scheme_scores[0] if scheme_scores[0][1] > 0 else (None, 0)
    used_context = False
    if not scheme and context_scheme_id:
        scheme, used_context = get_scheme(context_scheme_id), True
    topics = sorted(((t, _count(q, kws)) for t, kws in it["topics"].items()), key=lambda x: x[1], reverse=True)
    topic = topics[0][0] if topics[0][1] > 0 else None

    hits = store().search(query, k=6)
    faq = None
    faq_score = 0
    for c in build_chunks():
        if c.get("keywords") and (not scheme or c["scheme"] == scheme["id"]):
            sc = _count(q, c["keywords"])
            if sc > faq_score:
                faq, faq_score = c, sc
    if faq and not scheme and faq_score < 2:
        faq = None
    if not scheme and faq:
        scheme = get_scheme(faq["scheme"])

    # Chunks for the LLM context: the chosen topic chunk first, then vector hits from the same scheme.
    ctx = []
    if scheme:
        want = faq["id"] if faq else f"{scheme['id']}:{topic or 'about'}"
        ctx = [c for c in build_chunks() if c["id"] == want] + [c for c, _ in hits if c["scheme"] == scheme["id"] and c["id"] != want][:3]
    return {
        "scheme": scheme, "topic": topic, "faq": faq, "scheme_score": scheme_score, "faq_score": faq_score,
        "used_context": used_context, "chunks": ctx, "vector_hits": [(c["id"], round(s, 3)) for c, s in hits[:4]],
        "out_of_scope": not scheme and _count(q, it["outOfScope"]) > 0,
        "greeting": _count(q, it["greetings"]) > 0 and len(q.split()) <= 4,
    }


def answer(text: str, lang_override: str = "auto", context_scheme_id: str | None = None) -> dict:
    dialect = normalize_dialect(text)
    detected = detect_language(text)
    lang = lang_override if lang_override in LANGS else detected["lang"]
    if lang not in LANGS:
        lang = "hi"
    r = retrieve(dialect["normalized"], context_scheme_id)
    base = {"lang": lang, "detected": detected, "dialect": dialect, "normalized": dialect["normalized"],
            "retrieval": {"vectorStore": store().name, "hits": r["vector_hits"]}}

    if r["out_of_scope"] or (not r["scheme"] and not r["topic"] and not r["greeting"]):
        return {**base, "text": UNSURE[lang], "confidence": "low", "score": 0.15, "sources": [], "helpline": "181", "provider": "backend-rag"}
    if not r["scheme"]:
        return {**base, "text": WHICH[lang], "confidence": "medium", "score": 0.5, "sources": [], "provider": "backend-rag"}

    s = r["scheme"]
    score = 0.45 + (0.25 if r["scheme_score"] else 0.15 if r["used_context"] else 0) + (0.25 if (r["faq_score"] or r["topic"]) else 0)
    score = min(0.97, score)
    confidence = "high" if score >= 0.8 else "medium" if score >= 0.55 else "low"
    sources = [{"title": s["sourceName"], "url": s["officialUrl"], "lastVerified": s["lastVerified"]}]

    # Template answer straight from the top verified chunk (always available, zero cost).
    top = r["chunks"][0] if r["chunks"] else None
    text_out = pick(top["text"], lang) if top else pick(s["simple"], lang)
    provider = f"backend-rag:{store().name}"

    if llm.available():
        generated = llm.grounded_answer(text, r["chunks"], lang)
        if generated:
            text_out = generated
            provider += f"+{llm.model_name()}"
            if llm.is_unsure(generated):
                confidence, score = "low", 0.2

    return {**base, "text": text_out, "schemeId": s["id"], "topic": (r["faq"] or {}).get("topic") or r["topic"] or "about",
            "confidence": confidence, "score": round(score, 2), "sources": sources, "helpline": s["helpline"]["number"], "provider": provider}
